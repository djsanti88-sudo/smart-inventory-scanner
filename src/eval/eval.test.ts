import { describe, it, expect } from "vitest";
import { writeFileSync, mkdirSync } from "node:fs";
import { runEval, formatReport } from "@/eval/runEval";

// Runnable MOCK eval (no live AI). Prints the baseline table to the console AND asserts the safety
// invariant. Run it directly with:  npx vitest run src/eval/eval.test.ts
// (the printed "BASELINE" block is the decode baseline used by docs/decode/IMPROVEMENT_PLAN.md).

describe("decode eval harness (mock baseline)", () => {
  const report = runEval();

  it("writes + prints the baseline table", () => {
    const out = formatReport(report);
    console.log("\n" + out);
    // Durable artifact (vitest swallows console.log on passing tests): the committed baseline.
    try {
      mkdirSync("docs/decode", { recursive: true });
      writeFileSync("docs/decode/eval-baseline.md", `# Decode eval baseline (mock/offline)\n\n_Generated by \`npx vitest run src/eval/eval.test.ts\`. Representative fixtures, NOT live._\n\n\`\`\`\n${out}\`\`\`\n`);
    } catch {
      // file write is best-effort; the assertions below are the real gate
    }
    expect(report.rows.length).toBe(report.summary.total);
  });

  it("HARD INVARIANT: FALSE auto-count rate is 0% (poison NEVER auto-counts)", () => {
    expect(report.summary.falseAutoCountRatePct).toBe(0);
    const poison = report.rows.find((r) => r.code === "745125495781")!;
    expect(poison.autoCount).toBe(false);
    expect(poison.falseAutoCount).toBe(false);
  });

  it("identity accuracy is measured over tires and is non-trivial", () => {
    expect(report.summary.identityAccuracyPct).toBeGreaterThan(0);
  });
});
